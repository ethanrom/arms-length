/** The exact prompts sent to the model. prompts.md is generated from these (run.ts --prompts), so the two cannot drift. */

export const MODEL_ID = "global.anthropic.claude-opus-5-5";

export const SYSTEM_PROMPT = "You answer with a single JSON object and nothing else: no markdown fence, no commentary.";

/** The six concerns of Test A, in the order they are asked, with the JSON key and our concern id for each. */
export const TEST_A_CONCERNS = [
  { key: "pores", label: "pores", ours: "pore" },
  { key: "dark_spots", label: "dark spots", ours: "age_spot" },
  { key: "fine_lines", label: "fine lines", ours: "wrinkle" },
  { key: "under_eye_shadows", label: "under-eye shadows", ours: "dark_circle" },
  { key: "redness", label: "redness", ours: "redness" },
  { key: "breakouts", label: "breakouts", ours: "acne" },
] as const;

export type TestAKey = (typeof TEST_A_CONCERNS)[number]["key"];

export function testAPrompt(): string {
  return [
    "This is a photo of a face. The person's interpupillary distance is about 63 mm.",
    "For an observer with perfect 20/20 vision, looking straight at this person in normal indoor light, give the farthest distance in metres at which each of these could still be seen: pores, dark spots, fine lines, under-eye shadows, redness, breakouts. If one is not present, say null.",
    `Reply with JSON only, in this shape, with a number of metres (or null) for each key: {${TEST_A_CONCERNS.map((c) => `"${c.key}": m`).join(", ")}}`,
  ].join("\n");
}

export function testBPrompt(diameterMm: number, contrastPct: number): string {
  return [
    "The image is a 60 mm x 60 mm patch of skin with a millimetre ruler printed along its bottom edge.",
    `The dark spot is ${diameterMm} mm across and ${contrastPct}% darker than the surrounding skin. Lighting is normal indoor. For an observer with perfect 20/20 vision looking straight at it, what is the farthest distance in metres at which the spot can still be seen?`,
    'Reply with JSON only, in this shape: {"distance_m": n, "reasoning_short": "..."}',
  ].join("\n");
}

export function promptsMarkdown(): string {
  const fence = "```";
  return `# Prompts

Generated by \`npx tsx eval/llm-baseline/run.ts --prompts\` from \`prompts.ts\`. These are the exact strings sent.

- Model: \`${MODEL_ID}\` on Amazon Bedrock, \`ConverseCommand\`.
- Inference config: \`maxTokens: 4000\` and nothing else (no temperature, topP, or thinking or budget settings).
- Each call is independent: one user message holding one image block followed by one text block, no history.

## System prompt (both tests)

${fence}text
${SYSTEM_PROMPT}
${fence}

## Test A: real-looking faces (image: \`fixtures/youcam/<persona>/input.jpg\`, sent unchanged)

${fence}text
${testAPrompt()}
${fence}

## Test B: synthetic patches (image: 600 x 600 px PNG, 10 px/mm; \`X\` in {1, 2, 4}, \`Y\` in {5, 15, 30})

${fence}text
${testBPrompt(1, 5).replace("1 mm across and 5%", "X mm across and Y%")}
${fence}

For example, the \`d2mm_c15\` patch gets X = 2 and Y = 15.
`;
}
