/**
 * Precompute the unit-contrast threshold tables used at runtime (research 1.7).
 * Run: npx tsx scripts/vision/build-tables.ts [--check]
 * Writes lib/vision/tables/*.json (Standard A, ModelFest luminance 30 cd/m^2). With --check nothing is written; the
 * script prints the largest difference between the committed tables and a fresh build.
 *
 * Tables (angular sizes in arcmin, thresholds as log10 of the Weber contrast of a unit-peak stimulus):
 *   gaussian.json   sd of a 2-D Gaussian blob                       200 points, 0.01 to 300 arcmin
 *   disk.json       equal-area diameter of a uniform disk           200 points
 *   softDisk.json   equal-area diameter of a Gaussian-blurred disk  200 points
 *   line.json       width of an infinitely long line                200 points
 *   lineLength.json width x length of a finite line                 40 x 46 grid
 *   patch.json      1-octave Gabor patch carrier frequency (cpd)    16 points, 0.25 to 45 cpd, half-octave steps
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { blobThreshold, gaborPatchThreshold, lineThreshold, lineThresholdInfinite, type BlobShape } from "../../lib/vision/shapes";
import { MODELFEST_LUMINANCE } from "../../lib/vision/params";

const outDir = join(dirname(fileURLToPath(import.meta.url)), "../../lib/vision/tables");
const check = process.argv.includes("--check");

const SIZE_MIN = 0.01;
const SIZE_MAX = 300;
const N1 = 200;
const MODEL = `Watson & Ahumada 2005 Standard A, ${MODELFEST_LUMINANCE} cd/m2, generated by scripts/vision/build-tables.ts`;

const round = (x: number) => Math.round(x * 1e5) / 1e5;
const logGrid = (min: number, max: number, n: number) =>
  Array.from({ length: n }, (_, i) => min * Math.pow(max / min, i / (n - 1)));

function table1d(name: string, fn: (sizeDeg: number) => number) {
  const sizes = logGrid(SIZE_MIN, SIZE_MAX, N1);
  return {
    name,
    model: MODEL,
    unit: "arcmin",
    sizeMin: SIZE_MIN,
    sizeMax: SIZE_MAX,
    n: N1,
    log10T: sizes.map((s) => round(Math.log10(fn(s / 60)))),
  };
}

const W_MIN = 0.02;
const W_MAX = 120;
const NW = 40;
const L_MIN = 0.02;
const L_MAX = 360;
const NL = 46;

function lineLengthTable() {
  const widths = logGrid(W_MIN, W_MAX, NW);
  const lengths = logGrid(L_MIN, L_MAX, NL);
  const log10T: number[] = [];
  for (const w of widths) {
    let firstValid: number | null = null;
    const row: number[] = [];
    for (const l of lengths) {
      if (l < w * 0.9999) {
        row.push(NaN); // filled below with the square value
        continue;
      }
      const v = round(Math.log10(lineThreshold(w / 60, l / 60)));
      if (firstValid === null) firstValid = v;
      row.push(v);
    }
    log10T.push(...row.map((v) => (Number.isNaN(v) ? (firstValid as number) : v)));
  }
  return {
    name: "lineLength",
    model: MODEL,
    unit: "arcmin",
    widthMin: W_MIN,
    widthMax: W_MAX,
    nWidth: NW,
    lengthMin: L_MIN,
    lengthMax: L_MAX,
    nLength: NL,
    /** Row-major: index = iWidth * nLength + iLength. Entries with length < width repeat the first valid length. */
    log10T,
  };
}

function patchTable() {
  const n = 16;
  const f0s = Array.from({ length: n }, (_, k) => 0.25 * Math.pow(2, k / 2));
  return {
    name: "patch",
    model: MODEL,
    unit: "cpd",
    f0Min: f0s[0],
    f0Max: f0s[n - 1],
    n,
    log10T: f0s.map((f) => round(Math.log10(gaborPatchThreshold(f)))),
  };
}

const jobs: { file: string; build: () => unknown }[] = [
  ...(["gaussian", "disk", "softDisk"] as BlobShape[]).map((shape) => ({
    file: `${shape}.json`,
    build: () => table1d(shape, (s) => blobThreshold(shape, s)),
  })),
  { file: "line.json", build: () => table1d("line", (w) => lineThresholdInfinite(w)) },
  { file: "lineLength.json", build: lineLengthTable },
  { file: "patch.json", build: patchTable },
];

mkdirSync(outDir, { recursive: true });
for (const job of jobs) {
  const t0 = Date.now();
  const fresh = job.build() as { log10T: number[] };
  const path = join(outDir, job.file);
  if (check) {
    if (!existsSync(path)) {
      console.log(`${job.file}: missing`);
      continue;
    }
    const old = JSON.parse(readFileSync(path, "utf8")) as { log10T: number[] };
    let worst = 0;
    fresh.log10T.forEach((v, i) => (worst = Math.max(worst, Math.abs(20 * (v - old.log10T[i])))));
    console.log(`${job.file}: max difference ${worst.toFixed(4)} dB (${Date.now() - t0} ms)`);
  } else {
    writeFileSync(path, JSON.stringify(fresh) + "\n");
    console.log(`${job.file}: written (${Date.now() - t0} ms)`);
  }
}
